const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
const htmlPath = path.join(__dirname, 'index.html');
const outDir = path.join(__dirname, 'js');
const outPath = path.join(outDir, 'env.js');

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

// Whitelisted client-safe environment variables
const envVars = {
  FIREBASE_API_KEY: '',
  FIREBASE_DATABASE_URL: '',
  CENTER_NAME: 'Apex Tuition Centre',
  MAX_UPLOAD_KB: 1500
};

if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf-8');
  content.split('\n').forEach(line => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (key in envVars) {
        if (key === 'MAX_UPLOAD_KB') {
          envVars[key] = parseInt(val, 10) || 1500;
        } else {
          envVars[key] = val;
        }
      }
    }
  });
} else {
  console.warn('.env file not found. Using fallback defaults.');
}

// Clean trailing slash from database URL if present
if (envVars.FIREBASE_DATABASE_URL && envVars.FIREBASE_DATABASE_URL.endsWith('/')) {
  envVars.FIREBASE_DATABASE_URL = envVars.FIREBASE_DATABASE_URL.slice(0, -1);
}

// Safe validation for missing required client configuration
if (!envVars.FIREBASE_API_KEY) {
  console.warn('[SECURITY/CONFIG WARNING] FIREBASE_API_KEY is not defined in .env.');
}
if (!envVars.FIREBASE_DATABASE_URL) {
  console.warn('[SECURITY/CONFIG WARNING] FIREBASE_DATABASE_URL is not defined in .env.');
}

// Write standalone js/env.js for backwards compatibility
const fileContent = `/* Auto-generated by build.js - Do not edit directly */\nwindow.__ENV__ = ${JSON.stringify(envVars, null, 2)};\n`;
fs.writeFileSync(outPath, fileContent, 'utf-8');
console.log(`Successfully generated ${outPath}`);

// Inject environment directly into index.html so it NEVER fails on 404/caching
if (fs.existsSync(htmlPath)) {
  let html = fs.readFileSync(htmlPath, 'utf-8');
  const startTag = '<!-- [APP_ENV_START] -->';
  const endTag = '<!-- [APP_ENV_END] -->';
  const formattedJson = JSON.stringify(envVars, null, 2).replace(/\n/g, '\n    ');
  const injectionBlock = `${startTag}\n  <script id="app-env">\n    window.__ENV__ = ${formattedJson};\n  </script>\n  ${endTag}`;

  if (html.includes(startTag) && html.includes(endTag)) {
    const pattern = new RegExp(`${startTag}[\\s\\S]*?${endTag}`);
    html = html.replace(pattern, injectionBlock);
  } else if (html.includes('<script src="js/env.js')) {
    html = html.replace(/\s*<script src="js\/env\.js.*?"[^>]*><\/script>/, '\n  ' + injectionBlock);
  }

  // Ensure XLSX and JSZip are included in index.html if not already present
  if (!html.includes('xlsx.full.min.js')) {
    html = html.replace(startTag, `<script src="js/xlsx.full.min.js?v=3.8"></script>\n  <script src="js/jszip.min.js?v=3.8"></script>\n  ${startTag}`);
  }

  fs.writeFileSync(htmlPath, html, 'utf-8');
  console.log('Successfully synchronized environment and libraries in index.html');
}
